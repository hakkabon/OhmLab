// swift-tools-version: 6.0
// OhmLab Package.swift
//
// Layout:
//   • OhmLabCore   — the platform-agnostic core: schematic model, connectivity,
//                    netlist parser/builder, the native MNA engine, diagnostics,
//                    persistence, and interchange. Shared by the app, the CLI,
//                    and the tests.
//   • OhmLab       — the SwiftUI app (a thin shell over OhmLabCore).
//   • ohm          — the headless/batch command-line front end.
//
// Engine:
//   • Default:          the built-in pure-Swift MNA engine (OhmLabCore).
//   • Optional Rust:    an `audio-spice-core` crate can be linked behind the
//                       same EngineBackend facade once its C static library has
//                       been produced (`scripts/build-rust-core.sh`). The Swift
//                       engine remains the default and the reference.
//
// UniFFI Swift bindings, when used, are generated by
// `uniffi-bindgen generate --language swift`.

import PackageDescription

let package = Package(
    name: "OhmLab",

    // ── Supported platforms ──────────────────────────────────────────────────
    platforms: [
        .macOS(.v14),   // Charts, NavigationSplitView, Grid
        .iOS(.v17),     // iPadOS SwiftUI app target
    ],

    // ── Products ─────────────────────────────────────────────────────────────
    products: [
        .library(name: "OhmLabCore", targets: ["OhmLabCore"]),
        .executable(name: "OhmLab", targets: ["OhmLab"]),
    ],

    // ── Dependencies ─────────────────────────────────────────────────────────
    dependencies: [],

    // ── Targets ──────────────────────────────────────────────────────────────
    targets: [
        // ── Core (no app lifecycle) ───────────────────────────────────────────
        .target(
            name: "OhmLabCore",
            path: "Sources/OhmLabCore",
            swiftSettings: [
                // Uncomment to activate the linked Rust engine path:
                // .define("OHMLAB_RUST_CORE"),
            ]
        ),

        // ── SwiftUI app shell ─────────────────────────────────────────────────
        .executableTarget(
            name: "OhmLab",
            dependencies: ["OhmLabCore"],
            path: "Sources/OhmLab"
        ),

        // ── Tests ─────────────────────────────────────────────────────────────
        .testTarget(
            name: "OhmLabTests",
            dependencies: ["OhmLabCore"],
            path: "Tests/OhmLabTests"
        ),
    ]
)
