// swift-tools-version: 6.0
// OhmLab Package.swift
//
// Layout:
//   • OhmLabCore   — the platform-agnostic core: schematic model, connectivity,
//                    netlist parser/builder, the native MNA engine, diagnostics,
//                    persistence, and interchange. Shared by the app, the CLI,
//                    and the tests.
//   • OhmLab       — the SwiftUI app (a thin shell over OhmLabCore).
//   • ohm          — the headless/batch command-line front end.
//
// Engine:
//   • Default:  the built-in pure-Swift MNA engine (OhmLabCore). No Rust
//               toolchain is required for a normal build or test run.
//   • Optional: a Rust `ohm-core` crate (rust/ohm-core) can be linked behind the
//               same EngineBackend façade. It provides DC/AC for linear R/C/L/V/I
//               circuits and returns versioned JSON over a Circuit IR C ABI.
//
// ── Enabling the Rust core (optional) ────────────────────────────────────────
//   1. scripts/build-rust-core.sh          # runs cargo test + builds libohm_core.a
//   2. OHMLAB_RUST_CORE=1 swift test
//   3. RustEngineBackend.swift compiles in automatically and can be selected
//      at launch with
//      `SimulationEngine.register(RustEngineBackend(), makeDefault: true)`.
//
// UniFFI Swift bindings, if ever preferred over the JSON C ABI, are generated by
// `uniffi-bindgen generate --language swift`.

import PackageDescription
import Foundation

let rustCoreEnabled = ProcessInfo.processInfo.environment["OHMLAB_RUST_CORE"] == "1"
let packageRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
var coreDependencies: [Target.Dependency] = [
    .product(name: "NumericCoreOptimization", package: "Swift-NumericCore"),
]
var coreLinkerSettings: [LinkerSetting]? = nil
if rustCoreEnabled {
    coreDependencies.append("CCOhmCore")
    coreLinkerSettings = [
        .unsafeFlags(["-L\(packageRoot)/rust/ohm-core/target/release"]),
        .linkedLibrary("ohm_core"),
    ]
}

var packageTargets: [Target] = []
if rustCoreEnabled {
    packageTargets.append(.systemLibrary(name: "CCOhmCore", path: "Sources/CCOhmCore"))
}
packageTargets.append(contentsOf: [
    .target(
        name: "OhmLabCore",
        dependencies: coreDependencies,
        path: "Sources/OhmLabCore",
        linkerSettings: coreLinkerSettings
    ),
    .executableTarget(
        name: "OhmLab",
        dependencies: ["OhmLabCore"],
        path: "Sources/OhmLab"
    ),
    .executableTarget(
        name: "OhmLabCLI",
        dependencies: ["OhmLabCore"],
        path: "Sources/OhmLabCLI"
    ),
    .testTarget(
        name: "OhmLabTests",
        dependencies: ["OhmLabCore"],
        path: "Tests/OhmLabTests",
        resources: [.copy("Fixtures")]
    ),
])

let package = Package(
    name: "OhmLab",

    // ── Supported platforms ──────────────────────────────────────────────────
    platforms: [
        .macOS(.v14),   // Charts, NavigationSplitView, Grid
        .iOS(.v17),     // iPadOS SwiftUI app target
    ],

    // ── Products ─────────────────────────────────────────────────────────────
    products: [
        .library(name: "OhmLabCore", targets: ["OhmLabCore"]),
        .executable(name: "OhmLab", targets: ["OhmLab"]),
        .executable(name: "ohm", targets: ["OhmLabCLI"]),
    ],

    // ── Dependencies ─────────────────────────────────────────────────────────
    dependencies: [
        // NumericCore's circuit-analysis API is currently provisional and has
        // not reached a tagged release. Pin the reviewed revision exactly until
        // the API ships in a stable release, then move this to a semantic range.
        .package(
            url: "https://github.com/hakkabon/Swift-NumericCore.git",
            revision: "7318e8c470079b5255142d223750c251e9b2cfe7"
        ),
    ],

    // ── Targets ──────────────────────────────────────────────────────────────
    targets: packageTargets
)
